"""
Module: train_neural_net.py
Report Section: Chapter 7 Training Strategies & PINN Evaluation

This script orchestrates training and evaluation of the Physics-Informed Neural
Network (PINN) for Gaia-CALSPEC spectral recalibration. It handles input/output
scaling, optional heteroscedastic uncertainty, checkpoint loading and saving,
and the 2-stage adaptive training strategy used to learn the physics-informed
spectral correction model.
"""

import os
import joblib
import numpy as np
import torch
from torch.utils.data import DataLoader, TensorDataset
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

from src.models.neural_net import SpectralRecalibrationMLP
from src.train.loss.original_loss import PhysicsInformedLoss, adaptive_physics_wrapper
from src.train.training_functions.adp_training_strategies import train_2stage_adaptive
from src.utils.metrics.alternative_metrics import (
    calculate_band_errors,
    calculate_mape,
    calculate_reduced_chi_square,
)


def train_network(mode: str = "spectrum"):
    """
    Executes or skips the training pipeline for the PINN based on whether a 
    pre-trained joblib checkpoint exists. It then evaluates the model on the test set.
    """
    print("=" * 60)
    print(f"[7.2] INITIATING PINN TRAINING PIPELINE | MODE: {mode.upper()}")
    print("=" * 60)

    # 1. Path and Dimensionality Configuration
    config = {
        "spectrum": ("data/processed/X.npy", 300),
        "features": ("data/processed/X_features.npy", 5),
    }
    if mode not in config:
        raise ValueError("Mode must be either 'spectrum' or 'features'.")

    features_path, input_dim = config[mode]
    targets_path = "data/processed/Y.npy"
    # Path to optional stochastic variance matrix (Poisson noise + read-out noise).
    sigma_path = "data/processed/Sigma.npy"

    # Ensure the required preprocessed data files are present before continuing.
    if not (os.path.exists(features_path) and os.path.exists(targets_path)):
        print(f"[!] Error: Dataset binaries not found for mode '{mode}'.")
        return

    # 2. Data Loading
    X, Y = np.load(features_path), np.load(targets_path)

    # Load Sigma only when it has been generated by preprocessing.
    # This allows the same training code to run with or without uncertainty data.
    has_sigma = os.path.exists(sigma_path)
    Sigma = np.load(sigma_path) if has_sigma else None

    # Unpack splits dynamically depending on presence of Sigma
    splits = train_test_split(
        *(arr for arr in (X, Y, Sigma) if arr is not None),
        test_size=0.2,
        random_state=42,
    )
    X_train, X_test, Y_train, Y_test = splits[:4]
    Sigma_train = splits[4] if has_sigma else None

    # 3. Data Scaling & Normalization
    # Physical scaling: normalize target fluxes by the maximum absolute training flux.
    # This keeps the model stable by working in a consistent relative flux range.
    Y_max = float(np.max(np.abs(Y_train)))
    scalers_dict = {"Y_max": Y_max}

    if mode == "spectrum":
        X_train_scaled = X_train / Y_max
        X_test_scaled = X_test / Y_max
    else:
        # In feature mode, standardize the input parameters and still scale
        # the output spectrum by Y_max to preserve physical units.
        scaler_X = StandardScaler()
        X_train_scaled = scaler_X.fit_transform(X_train)
        X_test_scaled = scaler_X.transform(X_test)
        scalers_dict["scaler_X"] = scaler_X

    Y_train_scaled = Y_train / Y_max
    # Mathematical scaling: variances scale with the square of the flux scale.
    Sigma_train_scaled = Sigma_train / (Y_max**2) if has_sigma else None

    # 4. Device and Model Setup
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"-> Computation Device allocated: {device}")

    # Dynamically configure the hidden layer architecture for the MLP.
    # The shape [64, 32, 64] is chosen to allow a compact residual mapping
    # with enough capacity for spectral corrections while avoiding overfitting.
    hidden_architecture = [64, 32, 64]

    model = SpectralRecalibrationMLP(
        input_dim=input_dim,
        output_dim=300,
        hidden_dims=hidden_architecture,
        dropout_rate=0.2,
    ).to(device)

    # Convert scaled arrays into tensors directly on the allocated compute device.
    to_tensor = lambda arr: (
        torch.tensor(arr, dtype=torch.float32, device=device)
        if arr is not None
        else None
    )
    X_train_t = to_tensor(X_train_scaled)
    Y_train_t = to_tensor(Y_train_scaled)
    Sigma_train_t = to_tensor(Sigma_train_scaled)

    # Create a dynamic DataLoader that includes Sigma when available.
    # This enables the same training loop to support uncertainty-aware and
    # standard training modes without branching in the optimizer.
    train_tensors = [t for t in (X_train_t, Y_train_t, Sigma_train_t) if t is not None]
    train_loader = DataLoader(
        TensorDataset(*train_tensors), batch_size=4, shuffle=True
    )

    # 5. Physics Loss Engine & 2-Stage Training
    # Setup physics loss evaluation engine.
    # The loss uses the same wavelength grid as the spectral output channels.
    wave_grid = torch.linspace(330.0, 1050.0, 300, device=device)
    pinn_loss_engine = PhysicsInformedLoss(wavelength_grid=wave_grid)

    # Wrap the physics loss criterion so it can accept optional stochastic noise.
    # The wrapper is passed into the training loop and decouples loss logic
    # from the dataset shape handling.
    physics_criterion = lambda m, x, y, s=None: adaptive_physics_wrapper(
        m, x, y, pinn_loss_engine, s
    )

    # Execute 2-Stage Adaptive Training.
    # - model: the neural network to train.
    # - dataloader: minibatch generator for stochastic Adam updates.
    # - X_full / Y_full: full training tensors used for second-stage L-BFGS.
    # - physics_criterion: function returning Huber/flux/shape metrics.
    # - Sigma_full: optional uncertainty matrix used by the physics loss.
    model = train_2stage_adaptive(
        model=model,
        dataloader=train_loader,
        X_full=X_train_t,
        Y_full=Y_train_t,
        physics_criterion=physics_criterion,
        Sigma_full=Sigma_train_t,
        epochs_adam=300,
        steps_lbfgs=10,
    )

    # 6. Checkpoint Serialization
    # Serialize checkpoint mapping.
    # The checkpoint stores the trained state dict and the scaling metadata
    # required to apply the model later with consistent input/output scaling.
    output_dir = "results/models/pinn"
    os.makedirs(output_dir, exist_ok=True)
    save_path = os.path.join(output_dir, f"pinn_{mode}.joblib")

    checkpoint = {
        "model_state_dict": model.cpu().state_dict(),
        "input_dim": input_dim,
        "hidden_dims": hidden_architecture,
        "output_dim": 300,
        "scalers": scalers_dict,
    }
    joblib.dump(checkpoint, save_path)
    print(f"    [+] Model & Scalers successfully saved via joblib to: {save_path}")

    # 7. Validation Set Evaluation
    print("\n" + "=" * 60)
    print(">>> Evaluating PINN on Validation Set")
    print("=" * 60)

    model.to(device).eval()
    with torch.no_grad():
        # Predict on validation inputs and restore predictions to absolute physical flux units.
        Y_pred = model(to_tensor(X_test_scaled)).detach().cpu().numpy() * Y_max

    # Flatten arrays because alternative_metrics expects 1-D arrays
    Y_test_flat = Y_test.flatten()
    Y_pred_flat = Y_pred.flatten()

    # Create the physical wavelength grid and repeat it for all test samples
    wave_grid_np = np.linspace(330.0, 1050.0, 300)
    wave_flat = np.tile(wave_grid_np, len(Y_test))

    # Compute alternative domain-specific metrics
    mape = calculate_mape(Y_test_flat, Y_pred_flat)
    chi2 = calculate_reduced_chi_square(Y_test_flat, Y_pred_flat)
    band_errs = calculate_band_errors(wave_flat, Y_test_flat, Y_pred_flat)

    print(f"    -> Final MAPE (%)             : {mape:.4f}%")
    print(f"    -> Final Reduced Chi-Square    : {chi2:.4e}")
    print(f"    -> MAE Blue Band (<500nm)     : {band_errs['blue']:.4e}")
    print(f"    -> MAE Green Band (500-700nm) : {band_errs['green']:.4e}")
    print(f"    -> MAE Red Band (>700nm)      : {band_errs['red']:.4e}\n")
    print("=" * 60 + "\n")


if __name__ == "__main__":
    train_network(mode="spectrum")

    feat_path = "data/processed/X_features.npy"
    if os.path.exists(feat_path):
        train_network(mode="features")
    else:
        print(f"[i] Skipping 'features' mode: '{feat_path}' not found.")