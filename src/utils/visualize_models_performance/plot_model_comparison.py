"""
Module: plot_model_comparison.py

Visualization module for the Residual Physics-Informed Neural Network (PINN).

This script is responsible for generating quantitative and qualitative validation 
plots by reading the exported ".npz" inference files. It compares the uncalibrated 
Gaia spectra, the CALSPEC ground-truth references and the PINN predictions across 
multiple samples.
"""

import os
import numpy as np
import matplotlib.pyplot as plt


def generate_plots_from_file(input_filepath: str, output_dir: str, num_samples: int = 5):
    """
    Reads the inference results from a compressed .npz archive and generates 
    detailed validation plots for a specified number of stellar samples.

    This function extracts the wavelength grid, original spectra, reference spectra, 
    baseline predictions, and PINN predictions from the provided `.npz` file. 
    For each sample, it generates a two-panel figure:
    1. The top panel displays the absolute flux of all four spectra.
    2. The bottom panel displays the percentage residual relative to the 
       peak flux of the reference spectrum (aligned with the Peak-Normalized MAE metric).
    The resulting figures are saved as high-resolution PNG files.

    Args:
    - input_filepath (str): The full path to the `.npz` file containing the 
        exported inference data (e.g., generated by `export_test_predictions`).
    - output_dir (str): The destination directory where the generated validation 
        plots will be saved. The directory is created if it does not exist.
    - num_samples (int, optional): The maximum number of samples to plot, 
        starting from the first index. If the dataset contains fewer samples 
        than requested, it will plot all available samples. Defaults to 5.

    Returns:
    - None: This function does not return any Python objects. It writes image 
        files directly to the filesystem.

    Raises:
    - FileNotFoundError: If the `.npz` file specified by `input_filepath` does not exist.
    """
    if not os.path.exists(input_filepath):
        raise FileNotFoundError(f"Results file not found at: {input_filepath}")

    data = np.load(input_filepath)
    
    wave = data["wave"]
    X_orig = data["X_orig"]
    Y_ref = data["Y_ref"]
    X_pinn = data["X_pinn"]
    X_huang = data["X_huang"] if "X_huang" in data else None

    os.makedirs(output_dir, exist_ok=True)
    samples_to_plot = min(num_samples, X_orig.shape[0])

    print(f"\n[>] Generating {samples_to_plot} figures from the archive: {input_filepath}")

    for i in range(samples_to_plot):
        has_baseline = True
        X_huang_baseline = np.zeros_like(X_orig[i])

        fig, (ax1, ax2) = plt.subplots(
            2, 1, 
            figsize=(12, 8), 
            gridspec_kw={"height_ratios": [3, 1]}, 
            sharex=True
        )

        # Top Panel: Absolute Flux
        ax1.plot(wave, Y_ref[i], label="CALSPEC Reference (Y)", color="black", alpha=0.85, linewidth=2)
        ax1.plot(wave, X_orig[i], label="Original Gaia BP/RP (X)", color="#4f88f3", alpha=0.6, linewidth=1.5)
        if X_huang is not None and np.any(X_huang[i] > 0):
            ax1.plot(
                wave, X_huang[i], 
                label="Huang et al. 2024 Baseline", 
                color="#00cf49", alpha=0.9, linewidth=1.5, linestyle="--"
            )
        ax1.plot(wave, X_pinn[i], label="PINN Prediction (X * R)", color="#e63946", alpha=0.8, linewidth=1.5)

        ax1.set_title(f"Blind Test PINN vs Baseline | Star Index: {i:03d}")
        ax1.set_ylabel("Absolute Flux")
        ax1.grid(True, linestyle="--", alpha=0.4)
        ax1.legend()

        # Bottom Panel: Percentage Residual (%)
        # Aligned with Peak-Normalized MAE calculation
        peak_flux = np.max(Y_ref[i])
        res_original_pct = ((X_orig[i] - Y_ref[i]) / peak_flux) * 100.0
        res_pinn_pct = ((X_pinn[i] - Y_ref[i]) / peak_flux) * 100.0

        ax2.axhline(0.0, color="black", linestyle="-", linewidth=1.2, alpha=0.85)
        ax2.plot(wave, res_original_pct, label="Original Gaia Residual", color="#4f88f3", alpha=0.75, linewidth=1.0)

        if X_huang is not None and np.any(X_huang[i] > 0):
            res_baseline_pct = ((X_huang[i] - Y_ref[i]) / peak_flux) * 100.0
            ax2.plot(
                wave, res_baseline_pct, 
                label="Huang Baseline Residual", 
                color="#00cf49", alpha=0.8, linewidth=1.5, linestyle="--"
            )
        ax2.plot(wave, res_pinn_pct, label="PINN Residual", color="#e63946", alpha=0.9, linewidth=1.5)

        ax2.set_xlabel("Wavelength [nm]")
        ax2.set_ylabel("Residual (%)")
        ax2.set_ylim(-20, 20)
        ax2.grid(True, linestyle="--", alpha=0.4)
        ax2.legend(loc="upper right", fontsize="small")

        plt.tight_layout()
        save_path = os.path.join(output_dir, f"star_comparison_test_{i:03d}.png")
        plt.savefig(save_path, dpi=150, bbox_inches="tight")
        plt.close()

    print(f"[✓] Visualization complete. Plots saved to: {output_dir}")

if __name__ == "__main__":
    generate_plots_from_file("results/test_predictions_final.npz", "plots/validation_figures")